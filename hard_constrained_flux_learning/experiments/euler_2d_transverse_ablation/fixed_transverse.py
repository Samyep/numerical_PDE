"""Fixed Roe transverse transport for the dimension-consistent 2-D HCFL.

The learned part is exactly a shared six-cell normal flux.  This module adds
the standard transverse *increment-wave* transport used by Clawpack's classic
2-D wave-propagation algorithm (``transverse_waves=1``): the normal numerical
flux is converted to left- and right-going fluctuations, each fluctuation is
split by a fixed transverse Roe solver, and the resulting corner terms modify
the orthogonal face fluxes.

No parameter in this file is trainable.  We intentionally do not call this
``transverse_waves=2``: that option also propagates an explicit second-order
normal correction wave, which is absent from the retained 1-D HCFL scheme.
"""

from __future__ import annotations

from pathlib import Path
import sys

import numpy as np
import torch


HERE = Path(__file__).resolve().parent
BASE_EXPERIMENT = HERE.parent / "euler_2d_clawpack_quadrants"
sys.path.insert(0, str(BASE_EXPERIMENT))
import euler_2d_common as C  # noqa: E402
import transverse_models as M  # noqa: E402


METHOD_ID = "central_nonnegative6_fixed_transverse"
TRANSVERSE_LEVEL = 1


def transverse_roe_split_oriented(
    left: torch.Tensor,
    right: torch.Tensor,
    fluctuation: torch.Tensor,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Return fixed Roe ``B^- fluctuation`` and ``B^+ fluctuation``.

    Inputs use the normal frame ``(rho, m_n, m_t, E)``.  The formulas are the
    vectorized equivalent of Clawpack 5.10 ``rpt2_euler.f90``.  In particular,
    the transverse solver has three distinct speeds (the two acoustic waves
    and the repeated contact/shear speed), while preserving all four conserved
    components.
    """

    rho_left = left[..., 0].clamp_min(C.RHO_FLOOR)
    rho_right = right[..., 0].clamp_min(C.RHO_FLOOR)
    root_left = torch.sqrt(rho_left)
    root_right = torch.sqrt(rho_right)
    denominator = (root_left + root_right).clamp_min(1.0e-12)

    un_left = left[..., 1] / rho_left
    un_right = right[..., 1] / rho_right
    ut_left = left[..., 2] / rho_left
    ut_right = right[..., 2] / rho_right
    pressure_left = C.pressure_raw(left).clamp_min(C.PRESSURE_FLOOR)
    pressure_right = C.pressure_raw(right).clamp_min(C.PRESSURE_FLOOR)
    enthalpy_left = (left[..., 3] + pressure_left) / rho_left
    enthalpy_right = (right[..., 3] + pressure_right) / rho_right

    un = (root_left * un_left + root_right * un_right) / denominator
    ut = (root_left * ut_left + root_right * ut_right) / denominator
    enthalpy = (
        root_left * enthalpy_left + root_right * enthalpy_right
    ) / denominator
    velocity_squared = un.square() + ut.square()
    sound_squared = (
        (C.GAMMA - 1.0) * (enthalpy - 0.5 * velocity_squared)
    ).clamp_min(1.0e-12)
    sound = torch.sqrt(sound_squared)

    entropy_strength = (C.GAMMA - 1.0) / sound_squared * (
        (enthalpy - velocity_squared) * fluctuation[..., 0]
        + un * fluctuation[..., 1]
        + ut * fluctuation[..., 2]
        - fluctuation[..., 3]
    )
    shear_strength = fluctuation[..., 1] - un * fluctuation[..., 0]
    acoustic_plus_strength = (
        fluctuation[..., 2]
        + (sound - ut) * fluctuation[..., 0]
        - sound * entropy_strength
    ) / (2.0 * sound)
    acoustic_minus_strength = (
        fluctuation[..., 0] - entropy_strength - acoustic_plus_strength
    )

    wave_minus = acoustic_minus_strength[..., None] * torch.stack(
        (
            torch.ones_like(un),
            un,
            ut - sound,
            enthalpy - ut * sound,
        ),
        dim=-1,
    )
    wave_middle = torch.stack(
        (
            entropy_strength,
            entropy_strength * un + shear_strength,
            entropy_strength * ut,
            0.5 * entropy_strength * velocity_squared + shear_strength * un,
        ),
        dim=-1,
    )
    wave_plus = acoustic_plus_strength[..., None] * torch.stack(
        (
            torch.ones_like(un),
            un,
            ut + sound,
            enthalpy + ut * sound,
        ),
        dim=-1,
    )
    waves = torch.stack((wave_minus, wave_middle, wave_plus), dim=-2)
    speeds = torch.stack((ut - sound, ut, ut + sound), dim=-1)
    down = torch.einsum("...w,...wc->...c", speeds.clamp_max(0.0), waves)
    up = torch.einsum("...w,...wc->...c", speeds.clamp_min(0.0), waves)
    return down, up


def fixed_transverse_correction_oriented(
    state: torch.Tensor,
    normal_flux: torch.Tensor,
    dt: float,
) -> torch.Tensor:
    """Return the orthogonal-face correction generated by one normal sweep.

    ``state`` has shape ``[..., n_transverse, n_normal, 4]`` and
    ``normal_flux`` has one extra face in the normal direction.  Constant
    extrapolation is used in both directions, matching the data boundary
    condition and making the correction divergence vanish exactly for a
    genuinely one-dimensional state.
    """

    normal_cells = state.shape[-2]
    dx = C.DOMAIN_LENGTH / normal_cells
    padded = torch.cat((state[..., :1, :], state, state[..., -1:, :]), dim=-2)
    left = padded[..., :-1, :]
    right = padded[..., 1:, :]
    left_physical = C.physical_flux_oriented(left)
    right_physical = C.physical_flux_oriented(right)
    fluctuation_minus = normal_flux - left_physical
    fluctuation_plus = right_physical - normal_flux

    # Reuse one set of Roe averages for both normal fluctuations.  The extra
    # axis is only a two-member right-hand-side batch; it changes neither the
    # formulas nor their gradients.
    fluctuations = torch.stack((fluctuation_minus, fluctuation_plus), dim=-2)
    down, up = transverse_roe_split_oriented(
        left.unsqueeze(-2), right.unsqueeze(-2), fluctuations
    )
    down_minus, down_plus = down.unbind(dim=-2)
    up_minus, up_plus = up.unbind(dim=-2)

    # Each cell receives A^+ Delta q from its left face and A^- Delta q from
    # its right face.  Split their sum in the transverse Roe basis.
    down_by_cell = down_plus[..., :-1, :] + down_minus[..., 1:, :]
    up_by_cell = up_plus[..., :-1, :] + up_minus[..., 1:, :]

    # At a transverse face, collect the up-going contribution from the cell
    # below and the down-going contribution from the cell above.  Replication
    # supplies the standard transmissive ghost-cell contribution.
    up_from_below = torch.cat(
        (up_by_cell[..., :1, :, :], up_by_cell), dim=-3
    )
    down_from_above = torch.cat(
        (down_by_cell, down_by_cell[..., -1:, :, :]), dim=-3
    )
    return -0.5 * (dt / dx) * (up_from_below + down_from_above)


class HCFL2DNormalFixedTransverse(M.HCFL2DNormalCentralNonnegative):
    """Six-cell normal HCFL plus a parameter-free Roe corner transport."""

    def __init__(self, mean: np.ndarray, std: np.ndarray) -> None:
        super().__init__(mean, std)
        self.variant = METHOD_ID
        self.transverse_level = TRANSVERSE_LEVEL
        self.transverse_trainable_parameters = 0
        self.transverse_enabled = True

    def normal_raw_fluxes(
        self, state: torch.Tensor
    ) -> tuple[torch.Tensor, torch.Tensor]:
        flux_x = self.flux_net.forward_oriented(C.orient_state(state, "x"))
        flux_y_oriented = self.flux_net.forward_oriented(
            C.orient_state(state, "y")
        )
        return flux_x, C.deorient_flux(flux_y_oriented, "y")

    def raw_fluxes(
        self, state: torch.Tensor, dt: float | None = None
    ) -> tuple[torch.Tensor, torch.Tensor]:
        if dt is None:
            raise ValueError("Fixed transverse transport requires the current dt")
        state_x = C.orient_state(state, "x")
        state_y = C.orient_state(state, "y")
        normal_x = self.flux_net.forward_oriented(state_x)
        normal_y_oriented = self.flux_net.forward_oriented(state_y)
        normal_y = C.deorient_flux(normal_y_oriented, "y")
        if not self.transverse_enabled:
            return normal_x, normal_y

        correction_y = fixed_transverse_correction_oriented(
            state_x, normal_x, dt
        )
        correction_x_oriented = fixed_transverse_correction_oriented(
            state_y, normal_y_oriented, dt
        )
        correction_x = C.deorient_flux(correction_x_oriented, "y")
        return normal_x + correction_x, normal_y + correction_y


def make_model(mean: np.ndarray, std: np.ndarray) -> HCFL2DNormalFixedTransverse:
    return HCFL2DNormalFixedTransverse(mean, std)
