"""Generate genuinely two-dimensional training-only Euler trajectories.

The locked validation and test sets are not changed.  This generator adds
initial conditions in which transverse information is structurally necessary:
crossing discontinuities, corrugated contacts, shock/contact triple points,
shock-vortex interactions, colliding blast waves, and four-way collisions.

Every trajectory is generated by the same PyClaw 5.10 Roe reference solver,
at the same fine resolution, and with the same conservative restriction used
by the original diverse64 data set.
"""

from __future__ import annotations

import argparse
import hashlib
from importlib.metadata import version
import json
import math
from pathlib import Path
import sys
from typing import Any

import numpy as np


HERE = Path(__file__).resolve().parent
BASE = HERE.parent / "euler_2d_clawpack_quadrants"
sys.path.insert(0, str(BASE))
import generate_pyclaw_dataset as Q  # noqa: E402


FAMILIES = (
    "crossed_riemann",
    "corrugated_contact",
    "shock_contact_triple",
    "shock_vortex",
    "double_blast",
    "four_way_collision",
)


def _log_uniform(
    rng: np.random.Generator, lower: float, upper: float
) -> float:
    return float(np.exp(rng.uniform(math.log(lower), math.log(upper))))


def _random_state(
    rng: np.random.Generator,
    *,
    velocity_limit: float = 0.55,
    density_bounds: tuple[float, float] = (0.5, 2.0),
    pressure_bounds: tuple[float, float] = (0.4, 2.0),
) -> list[float]:
    return [
        _log_uniform(rng, *density_bounds),
        float(rng.uniform(-velocity_limit, velocity_limit)),
        float(rng.uniform(-velocity_limit, velocity_limit)),
        _log_uniform(rng, *pressure_bounds),
    ]


def _velocity(
    normal_velocity: float, tangential_velocity: float, theta: float
) -> tuple[float, float]:
    normal = np.asarray((math.cos(theta), math.sin(theta)))
    tangent = np.asarray((-math.sin(theta), math.cos(theta)))
    value = normal_velocity * normal + tangential_velocity * tangent
    return float(value[0]), float(value[1])


def _normal_state(
    rho: float,
    normal_velocity: float,
    tangential_velocity: float,
    pressure: float,
    theta: float,
) -> list[float]:
    u, v = _velocity(normal_velocity, tangential_velocity, theta)
    return [rho, u, v, pressure]


def sample_spec(family: str, seed: int, case_index: int) -> dict[str, Any]:
    family_index = FAMILIES.index(family)
    rng = np.random.default_rng(
        np.random.SeedSequence((seed, family_index, case_index))
    )
    theta = float(rng.uniform(0.0, math.pi))
    spec: dict[str, Any] = {
        "family": family,
        "case_index": case_index,
        "theta": theta,
    }

    if family == "crossed_riemann":
        separation = float(rng.uniform(math.pi / 6.0, 5.0 * math.pi / 12.0))
        if rng.random() < 0.5:
            separation = -separation
        spec.update(
            theta_second=theta + separation,
            centre=[float(rng.uniform(0.42, 0.58)), float(rng.uniform(0.42, 0.58))],
            offsets=[float(rng.uniform(-0.04, 0.04)), float(rng.uniform(-0.04, 0.04))],
            states=[_random_state(rng) for _ in range(4)],
        )
    elif family == "corrugated_contact":
        pressure = _log_uniform(rng, 0.45, 2.0)
        normal_velocity = float(rng.uniform(-0.4, 0.4))
        tangential_centre = float(rng.uniform(-0.2, 0.2))
        tangential_jump = float(rng.uniform(0.2, 0.75))
        spec.update(
            offset=float(rng.uniform(-0.08, 0.08)),
            amplitude=float(rng.uniform(0.025, 0.06)),
            wave_number=int(rng.integers(1, 4)),
            phase=float(rng.uniform(0.0, 2.0 * math.pi)),
            left=_normal_state(
                _log_uniform(rng, 0.45, 2.2),
                normal_velocity,
                tangential_centre - 0.5 * tangential_jump,
                pressure,
                theta,
            ),
            right=_normal_state(
                _log_uniform(rng, 0.45, 2.2),
                normal_velocity,
                tangential_centre + 0.5 * tangential_jump,
                pressure,
                theta,
            ),
        )
    elif family == "shock_contact_triple":
        downstream_pressure = _log_uniform(rng, 0.4, 1.2)
        downstream_density = _log_uniform(rng, 0.55, 1.5)
        downstream_normal_velocity = float(rng.uniform(-0.05, 0.2))
        spec.update(
            centre=[float(rng.uniform(0.42, 0.58)), float(rng.uniform(0.42, 0.58))],
            upstream=_normal_state(
                downstream_density * float(rng.uniform(1.15, 2.0)),
                float(rng.uniform(0.45, 0.9)),
                float(rng.uniform(-0.15, 0.15)),
                downstream_pressure * float(rng.uniform(1.8, 3.8)),
                theta,
            ),
            downstream_lower=_normal_state(
                downstream_density * float(rng.uniform(0.65, 0.95)),
                downstream_normal_velocity,
                float(rng.uniform(-0.45, -0.1)),
                downstream_pressure,
                theta,
            ),
            downstream_upper=_normal_state(
                downstream_density * float(rng.uniform(1.05, 1.55)),
                downstream_normal_velocity,
                float(rng.uniform(0.1, 0.45)),
                downstream_pressure,
                theta,
            ),
        )
    elif family == "shock_vortex":
        low_pressure = _log_uniform(rng, 0.45, 1.2)
        low_density = _log_uniform(rng, 0.55, 1.4)
        line_offset = float(rng.uniform(-0.06, 0.06))
        centre_normal = line_offset + float(rng.uniform(0.025, 0.09))
        centre_tangent = float(rng.uniform(-0.16, 0.16))
        normal = np.asarray((math.cos(theta), math.sin(theta)))
        tangent = np.asarray((-math.sin(theta), math.cos(theta)))
        centre = (
            np.asarray((0.5, 0.5))
            + centre_normal * normal
            + centre_tangent * tangent
        )
        spec.update(
            offset=line_offset,
            left=_normal_state(
                low_density * float(rng.uniform(1.15, 1.8)),
                float(rng.uniform(0.4, 0.8)),
                float(rng.uniform(-0.12, 0.12)),
                low_pressure * float(rng.uniform(1.7, 3.2)),
                theta,
            ),
            right=_normal_state(
                low_density,
                float(rng.uniform(-0.05, 0.15)),
                float(rng.uniform(-0.12, 0.12)),
                low_pressure,
                theta,
            ),
            vortex_centre=[float(centre[0]), float(centre[1])],
            vortex_width=float(rng.uniform(0.045, 0.085)),
            vortex_strength=float(rng.uniform(0.2, 0.5)),
            thermodynamic_amplitude=float(rng.uniform(-0.09, 0.09)),
        )
    elif family == "double_blast":
        centre = np.asarray(
            (float(rng.uniform(0.44, 0.56)), float(rng.uniform(0.44, 0.56)))
        )
        normal = np.asarray((math.cos(theta), math.sin(theta)))
        separation = float(rng.uniform(0.18, 0.30))
        first = centre - 0.5 * separation * normal
        second = centre + 0.5 * separation * normal
        spec.update(
            centres=[[float(first[0]), float(first[1])], [float(second[0]), float(second[1])]],
            widths=[float(rng.uniform(0.045, 0.075)), float(rng.uniform(0.045, 0.075))],
            pressure_factors=[float(rng.uniform(2.5, 5.0)), float(rng.uniform(2.5, 5.0))],
            density_factors=[float(rng.uniform(1.1, 1.6)), float(rng.uniform(1.1, 1.6))],
            base=_random_state(
                rng,
                velocity_limit=0.08,
                density_bounds=(0.75, 1.35),
                pressure_bounds=(0.45, 0.9),
            ),
        )
    elif family == "four_way_collision":
        spec.update(
            centre=[float(rng.uniform(0.44, 0.56)), float(rng.uniform(0.44, 0.56))],
            density=_log_uniform(rng, 0.7, 1.4),
            pressure=_log_uniform(rng, 0.5, 1.2),
            normal_speed=float(rng.uniform(0.35, 0.75)),
            tangential_speed=float(rng.uniform(0.25, 0.65)),
            density_factors=[float(rng.uniform(0.8, 1.2)) for _ in range(4)],
            pressure_factors=[float(rng.uniform(0.85, 1.15)) for _ in range(4)],
        )
    else:
        raise ValueError(f"Unknown family: {family}")
    return spec


def _coordinates(cells: int) -> tuple[np.ndarray, np.ndarray]:
    centres = (np.arange(cells, dtype=np.float64) + 0.5) / cells
    return np.meshgrid(centres, centres, indexing="xy")


def initial_state(cells: int, spec: dict[str, Any]) -> np.ndarray:
    xx, yy = _coordinates(cells)
    theta = float(spec["theta"])
    normal = np.asarray((math.cos(theta), math.sin(theta)))
    tangent = np.asarray((-math.sin(theta), math.cos(theta)))
    family = str(spec["family"])
    centre = np.asarray(spec.get("centre", (0.5, 0.5)))
    dx = xx - centre[0]
    dy = yy - centre[1]
    normal_coordinate = dx * normal[0] + dy * normal[1]
    tangent_coordinate = dx * tangent[0] + dy * tangent[1]

    if family == "crossed_riemann":
        theta_second = float(spec["theta_second"])
        second_normal = np.asarray(
            (math.cos(theta_second), math.sin(theta_second))
        )
        first = normal_coordinate - float(spec["offsets"][0])
        second = (
            dx * second_normal[0]
            + dy * second_normal[1]
            - float(spec["offsets"][1])
        )
        states = np.asarray(spec["states"])
        primitive = np.empty((cells, cells, 4), dtype=np.float64)
        primitive[(first >= 0.0) & (second >= 0.0)] = states[0]
        primitive[(first < 0.0) & (second >= 0.0)] = states[1]
        primitive[(first < 0.0) & (second < 0.0)] = states[2]
        primitive[(first >= 0.0) & (second < 0.0)] = states[3]
    elif family == "corrugated_contact":
        interface = (
            normal_coordinate
            - float(spec["offset"])
            - float(spec["amplitude"])
            * np.sin(
                2.0
                * math.pi
                * int(spec["wave_number"])
                * (tangent_coordinate + 0.5)
                + float(spec["phase"])
            )
        )
        primitive = np.empty((cells, cells, 4), dtype=np.float64)
        primitive[interface < 0.0] = np.asarray(spec["left"])
        primitive[interface >= 0.0] = np.asarray(spec["right"])
    elif family == "shock_contact_triple":
        primitive = np.empty((cells, cells, 4), dtype=np.float64)
        upstream = normal_coordinate < 0.0
        primitive[upstream] = np.asarray(spec["upstream"])
        primitive[~upstream & (tangent_coordinate < 0.0)] = np.asarray(
            spec["downstream_lower"]
        )
        primitive[~upstream & (tangent_coordinate >= 0.0)] = np.asarray(
            spec["downstream_upper"]
        )
    elif family == "shock_vortex":
        line = normal_coordinate - float(spec["offset"])
        primitive = np.empty((cells, cells, 4), dtype=np.float64)
        primitive[line < 0.0] = np.asarray(spec["left"])
        primitive[line >= 0.0] = np.asarray(spec["right"])
        vortex_centre = np.asarray(spec["vortex_centre"])
        vortex_dx = xx - vortex_centre[0]
        vortex_dy = yy - vortex_centre[1]
        width = float(spec["vortex_width"])
        envelope = np.exp(
            -(vortex_dx * vortex_dx + vortex_dy * vortex_dy)
            / (2.0 * width * width)
        )
        swirl = float(spec["vortex_strength"]) * envelope / width
        primitive[..., 1] += -swirl * vortex_dy
        primitive[..., 2] += swirl * vortex_dx
        thermal = np.exp(float(spec["thermodynamic_amplitude"]) * envelope)
        primitive[..., 0] *= thermal
        primitive[..., 3] *= thermal ** Q.GAMMA
    elif family == "double_blast":
        base = np.asarray(spec["base"])
        primitive = np.broadcast_to(base, (cells, cells, 4)).copy()
        for blast_centre, width, pressure_factor, density_factor in zip(
            spec["centres"],
            spec["widths"],
            spec["pressure_factors"],
            spec["density_factors"],
        ):
            blast_centre = np.asarray(blast_centre)
            radius_squared = (xx - blast_centre[0]) ** 2 + (
                yy - blast_centre[1]
            ) ** 2
            envelope = np.exp(-radius_squared / (2.0 * float(width) ** 2))
            primitive[..., 0] *= np.exp(math.log(float(density_factor)) * envelope)
            primitive[..., 3] *= np.exp(math.log(float(pressure_factor)) * envelope)
    elif family == "four_way_collision":
        normal_sign = np.where(normal_coordinate < 0.0, 1.0, -1.0)
        tangent_sign = np.where(tangent_coordinate < 0.0, 1.0, -1.0)
        normal_velocity = float(spec["normal_speed"]) * normal_sign
        tangent_velocity = float(spec["tangential_speed"]) * tangent_sign
        u = normal_velocity * normal[0] + tangent_velocity * tangent[0]
        v = normal_velocity * normal[1] + tangent_velocity * tangent[1]
        quadrant = (normal_coordinate >= 0.0).astype(np.int64) + 2 * (
            tangent_coordinate >= 0.0
        ).astype(np.int64)
        density_factors = np.asarray(spec["density_factors"])
        pressure_factors = np.asarray(spec["pressure_factors"])
        rho = float(spec["density"]) * density_factors[quadrant]
        pressure = float(spec["pressure"]) * pressure_factors[quadrant]
        primitive = np.stack((rho, u, v, pressure), axis=-1)
    else:
        raise ValueError(f"Unknown family: {family}")

    if not np.isfinite(primitive).all():
        raise RuntimeError(f"Non-finite primitive initial condition for {family}")
    if float(primitive[..., 0].min()) <= 0.0:
        raise RuntimeError(f"Non-positive density for {family}")
    if float(primitive[..., 3].min()) <= 0.0:
        raise RuntimeError(f"Non-positive pressure for {family}")
    return Q.primitive_to_conserved(primitive)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generate(args: argparse.Namespace) -> dict[str, Any]:
    specs = [sample_spec(args.family, args.seed, index) for index in range(args.count)]
    trajectories: list[np.ndarray] = []
    expected_times: np.ndarray | None = None
    for index, spec in enumerate(specs):
        fine_initial = initial_state(args.fine_cells, spec)
        trajectory, times = Q.run_pyclaw(
            fine_initial,
            args.coarse_cells,
            args.tfinal,
            args.output_intervals,
        )
        if expected_times is None:
            expected_times = times
        elif not np.array_equal(times, expected_times):
            raise RuntimeError("PyClaw returned inconsistent saved times")
        trajectories.append(trajectory)
        print(
            json.dumps(
                {
                    "completed": index + 1,
                    "count": len(specs),
                    "family": args.family,
                    "fine_cells": args.fine_cells,
                }
            ),
            flush=True,
        )

    metadata = {
        "purpose": "training-only genuinely two-dimensional data enrichment",
        "clawpack_version": version("clawpack"),
        "solver": "classic_pyclaw_euler_4wave_2D",
        "transverse_waves": 2,
        "boundary": "constant_extrapolation",
        "gamma": Q.GAMMA,
        "family": args.family,
        "count": len(specs),
        "seed": args.seed,
        "fine_cells": args.fine_cells,
        "coarse_cells": args.coarse_cells,
        "tfinal": args.tfinal,
        "output_intervals": args.output_intervals,
        "restriction": "conservative_block_average_of_conserved_variables",
        "generator_sha256": _sha256(Path(__file__)),
        "base_generator_sha256": _sha256(BASE / "generate_pyclaw_dataset.py"),
    }
    return {
        "q": np.stack(trajectories),
        "times": expected_times,
        "family_names": np.asarray([args.family] * len(specs)),
        "specs_json": np.asarray(json.dumps(specs, sort_keys=True)),
        "metadata_json": np.asarray(json.dumps(metadata, sort_keys=True)),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--family", choices=FAMILIES, required=True)
    parser.add_argument("--count", type=int, default=32)
    parser.add_argument("--seed", type=int, default=96001)
    parser.add_argument("--fine-cells", type=int, default=512)
    parser.add_argument("--coarse-cells", type=int, default=64)
    parser.add_argument("--tfinal", type=float, default=0.1)
    parser.add_argument("--output-intervals", type=int, default=20)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.count <= 0 or args.output_intervals <= 0:
        parser.error("Counts must be positive")
    if args.fine_cells % args.coarse_cells:
        parser.error("--fine-cells must be divisible by --coarse-cells")

    result = generate(args)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(args.output, **result)
    print(
        json.dumps(
            {
                "output": str(args.output),
                "shape": list(result["q"].shape),
                "family": args.family,
                "keys": sorted(result),
            },
            indent=2,
        ),
        flush=True,
    )


if __name__ == "__main__":
    main()
